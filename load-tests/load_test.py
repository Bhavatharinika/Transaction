#!/usr/bin/env python3
"""Load test for the transaction API. Measures what it actually observes; nothing is estimated.

  python load-tests/load_test.py --total 1000 --concurrency 100
  python load-tests/load_test.py --total 10000 --concurrency 200 --wait --dup-ratio 0.05 --json out.json

Reports: requests/sec, latency avg/p50/p95/p99/max, error rate, status-code mix, 202-under-100ms ratio,
queue depth (sampled from /api/health during the run), and with --wait the end-to-end completion rate.
Needs only httpx (pip install httpx).
"""
import argparse
import asyncio
import json
import random
import statistics
import time
import uuid
from datetime import datetime, timezone

import httpx


def pct(sorted_values: list[float], p: float) -> float:
    if not sorted_values:
        return float("nan")

    return sorted_values[
        min(
            len(sorted_values) - 1,
            int(round(p / 100 * (len(sorted_values) - 1))),
        )
    ]


def make_payload(tx_id: str) -> dict:
    return {
        "id": tx_id,
        "amount": round(random.uniform(1, 5000), 2),
        "currency": random.choice(["USD", "EUR", "GBP", "JPY"]),
        "description": "load test",
        "timestamp": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "metadata": {"source": "load-test"},
    }


async def sample_health(
    client: httpx.AsyncClient,
    samples: list[dict],
    stop: asyncio.Event,
) -> None:
    while not stop.is_set():
        try:
            body = (await client.get("/api/health")).json()

            samples.append(
                {
                    "t": time.time(),
                    "queueDepth": body["queue"]["depth"],
                    "inFlight": body["workers"]["inFlight"],
                    **{
                        k: body["transactions"].get(k)
                        for k in (
                            "pending",
                            "processing",
                            "completed",
                            "failed",
                        )
                    },
                }
            )
        except Exception:  # noqa: BLE001
            pass

        try:
            await asyncio.wait_for(stop.wait(), 1.0)
        except asyncio.TimeoutError:
            pass


async def cleanup_mock(mock_url: str | None) -> None:
    """Best-effort cleanup of downstream mock service before an end-to-end benchmark."""
    target_url = mock_url or "http://localhost:8080"

    try:
        async with httpx.AsyncClient(
            base_url=target_url,
            timeout=10,
        ) as mock_client:
            response = await mock_client.post("/cleanup")

            if response.status_code == 200:
                print(
                    f"[benchmark-isolation] Cleaned downstream mock at "
                    f"{target_url}: {response.json()}",
                    flush=True,
                )

    except Exception:  # noqa: BLE001
        pass


async def query_test_transactions_status(
    client: httpx.AsyncClient,
    ids: list[str],
    concurrency: int = 50,
) -> dict[str, int]:
    """Determine the status of every exact UUID belonging to this test.

    Never uses global database statistics as the source of truth for completion.
    """

    semaphore = asyncio.Semaphore(concurrency)

    counts = {
        "completed": 0,
        "failed": 0,
        "pending": 0,
        "processing": 0,
        "verifying": 0,
        "not_found": 0,
        "other": 0,
    }

    async def check(tx_id: str) -> None:
        async with semaphore:
            try:
                response = await client.get(
                    f"/api/transactions/{tx_id}"
                )

                if response.status_code == 200:
                    status = response.json().get("status")

                    if status in counts:
                        counts[status] += 1
                    else:
                        counts["other"] += 1

                elif response.status_code == 404:
                    counts["not_found"] += 1

                else:
                    counts["other"] += 1

            except Exception:  # noqa: BLE001
                counts["other"] += 1

    await asyncio.gather(*(check(tx_id) for tx_id in ids))

    return counts


async def wait_for_completion(
    client: httpx.AsyncClient,
    args,
    t0: float,
    health: list[dict],
    ids: list[str],
) -> dict:
    """Wait for the exact transactions generated by this benchmark.

    Completion is determined only from the supplied transaction IDs.
    Global /api/stats counters are intentionally not used because they
    may include transactions from previous or concurrent benchmark runs.
    """

    # Remove duplicate IDs while preserving order.
    unique_ids = list(dict.fromkeys(ids))

    deadline = time.time() + args.wait_timeout

    completed_ids: set[str] = set()
    failed_ids: set[str] = set()

    while time.time() < deadline:

        # Only poll transactions that have not reached a terminal state.
        remaining_ids = [
            tx_id
            for tx_id in unique_ids
            if tx_id not in completed_ids
            and tx_id not in failed_ids
        ]

        if not remaining_ids:
            break

        async def check_transaction(tx_id: str):
            try:
                response = await client.get(
                    f"/api/transactions/{tx_id}"
                )

                if response.status_code != 200:
                    return tx_id, None

                body = response.json()

                return tx_id, body.get("status")

            except httpx.HTTPError:
                return tx_id, None

        results = await asyncio.gather(
            *(check_transaction(tx_id) for tx_id in remaining_ids)
        )

        for tx_id, status in results:

            if status == "completed":
                completed_ids.add(tx_id)

            elif status == "failed":
                failed_ids.add(tx_id)

        # Every unique transaction has reached a terminal state.
        if len(completed_ids) + len(failed_ids) == len(unique_ids):
            break

        await asyncio.sleep(2)

    completed = len(completed_ids)
    failed = len(failed_ids)
    unfinished = len(unique_ids) - completed - failed

    took = time.perf_counter() - t0

    return {
        "submitted": len(unique_ids),
        "completed": completed,
        "failed": failed,
        "unfinished": unfinished,
        "invariantHolds": completed + failed + unfinished == len(unique_ids),
        "secondsFromStart": round(took, 1),
        "completionRatePerSecond": (
            round(completed / took, 2)
            if took > 0
            else 0
        ),
        "timedOut": unfinished > 0,
    }


async def run(args) -> dict:
    """Execute the benchmark."""

    if args.cleanup_mock:
        await cleanup_mock(args.mock_url)

    # Generate unique transaction IDs.
    ids = [str(uuid.uuid4()) for _ in range(args.total)]

    # Create payloads once so duplicate requests reuse the exact
    # same transaction ID and payload.
    payloads = {
        tx_id: make_payload(tx_id)
        for tx_id in ids
    }

    # Optional duplicate replay requests.
    requests: list[str] = list(ids)

    duplicate_count = int(args.total * args.dup_ratio)

    if duplicate_count > 0:
        requests.extend(
            random.choice(ids)
            for _ in range(duplicate_count)
        )

    random.shuffle(requests)

    latencies: list[float] = []
    statuses: dict[int, int] = {}
    errors: list[str] = []

    health_samples: list[dict] = []
    health_stop = asyncio.Event()

    t0 = time.perf_counter()

    limits = httpx.Limits(
        max_connections=max(args.concurrency * 2, 100),
        max_keepalive_connections=max(args.concurrency, 50),
    )

    timeout = httpx.Timeout(
        connect=10.0,
        read=30.0,
        write=30.0,
        pool=30.0,
    )

    async with httpx.AsyncClient(
        base_url=args.url,
        timeout=timeout,
        limits=limits,
    ) as client:

        health_task = asyncio.create_task(
            sample_health(
                client,
                health_samples,
                health_stop,
            )
        )

        semaphore = asyncio.Semaphore(args.concurrency)

        async def submit(tx_id: str) -> None:
            payload = payloads[tx_id]

            start = time.perf_counter()

            async with semaphore:
                try:
                    response = await client.post(
                        "/api/transactions",
                        json=payload,
                    )

                    elapsed_ms = (
                        time.perf_counter() - start
                    ) * 1000

                    latencies.append(elapsed_ms)

                    statuses[response.status_code] = (
                        statuses.get(response.status_code, 0) + 1
                    )

                    if response.status_code >= 400:
                        errors.append(
                            f"{tx_id}: "
                            f"HTTP {response.status_code}: "
                            f"{response.text[:300]}"
                        )

                except Exception as exc:  # noqa: BLE001
                    elapsed_ms = (
                        time.perf_counter() - start
                    ) * 1000

                    latencies.append(elapsed_ms)

                    errors.append(
                        f"{tx_id}: {type(exc).__name__}: {exc}"
                    )

        await asyncio.gather(
            *(submit(tx_id) for tx_id in requests)
        )

        submission_seconds = time.perf_counter() - t0

        result = {
            "totalUniqueTransactions": len(ids),
            "totalRequests": len(requests),
            "duplicateRequests": len(requests) - len(ids),
            "submissionSeconds": round(
                submission_seconds,
                3,
            ),
            "requestsPerSecond": round(
                len(requests) / submission_seconds,
                2,
            )
            if submission_seconds > 0
            else 0,
            "uniqueTransactionsPerSecond": round(
                len(ids) / submission_seconds,
                2,
            )
            if submission_seconds > 0
            else 0,
            "httpStatuses": statuses,
            "errors": errors[:20],
            "errorCount": len(errors),
            "healthSamples": health_samples,
        }

        if latencies:
            sorted_latencies = sorted(latencies)

            result["latencyMs"] = {
                "min": round(min(latencies), 2),
                "avg": round(
                    statistics.mean(latencies),
                    2,
                ),
                "p50": round(
                    pct(sorted_latencies, 50),
                    2,
                ),
                "p95": round(
                    pct(sorted_latencies, 95),
                    2,
                ),
                "p99": round(
                    pct(sorted_latencies, 99),
                    2,
                ),
                "max": round(max(latencies), 2),
            }

        # Measure exact end-to-end completion only when requested.
        if args.wait:
            result["completion"] = await wait_for_completion(
                client,
                args,
                t0,
                health_samples,
                ids,
            )

        # Final exact-ID status snapshot.
        result["transactionStatus"] = (
            await query_test_transactions_status(
                client,
                ids,
                concurrency=args.concurrency,
            )
        )

        health_stop.set()

        try:
            await health_task
        except Exception:  # noqa: BLE001
            pass

    return result


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    parser.add_argument(
        "--url",
        default="http://localhost:8000",
    )

    parser.add_argument(
        "--mock-url",
        default="http://localhost:8080",
        help="Mock posting service URL for cleanup",
    )

    parser.add_argument(
        "--cleanup-mock",
        action="store_true",
        help="invoke POST /cleanup on mock service before test",
    )

    parser.add_argument(
        "--total",
        type=int,
        default=1000,
    )

    parser.add_argument(
        "--concurrency",
        type=int,
        default=100,
    )

    parser.add_argument(
        "--dup-ratio",
        type=float,
        default=0.0,
        help="extra identical replays as a fraction of --total",
    )

    parser.add_argument(
        "--wait",
        action="store_true",
        help=(
            "also measure end-to-end completion "
            "(needs workers + mock running)"
        ),
    )

    parser.add_argument(
        "--wait-timeout",
        type=int,
        default=600,
    )

    parser.add_argument(
        "--json",
        help="write full results to this file",
    )

    args = parser.parse_args()

    result = asyncio.run(run(args))

    print(
        json.dumps(
            result,
            indent=2,
        )
    )

    if args.json:
        with open(args.json, "w") as fh:
            json.dump(
                result,
                fh,
                indent=2,
            )


if __name__ == "__main__":
    main()